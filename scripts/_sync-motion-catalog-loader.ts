/**
 * Loader for sync-motion-catalog.mjs — imports MOTION_EFFECTS and prints
 * the generated markdown catalog to stdout.
 */
import {
  listMotionEffects,
  type MotionEffect,
  type MotionEffectCategory,
} from '../src/components/modules/block-editor/motion/motionLibrary';

const CATEGORY_ORDER: MotionEffectCategory[] = [
  'entrance',
  'text',
  'scroll',
  'image',
  'hover',
  'loop',
  'special',
];

const formatDefaults = (effect: MotionEffect): string => {
  const d = effect.defaults;
  const parts = [
    `trigger=${d.trigger}`,
    `duration=${d.duration}`,
    `ease=${d.ease}`,
  ];
  if (d.start) parts.push(`start=${d.start}`);
  if (d.end) parts.push(`end=${d.end}`);
  if (d.stagger != null) parts.push(`stagger=${d.stagger}`);
  if (d.repeat != null) parts.push(`repeat=${d.repeat}`);
  return parts.join(', ');
};

const effects = listMotionEffects();
const byCategory = new Map<MotionEffectCategory, string[]>();
for (const cat of CATEGORY_ORDER) byCategory.set(cat, []);
for (const effect of effects) {
  const list = byCategory.get(effect.meta.category) ?? [];
  list.push(effect.id);
  byCategory.set(effect.meta.category, list);
}

const lines: string[] = [
  '<!-- AUTO-GENERATED by yarn motion:catalog — DO NOT EDIT BY HAND -->',
  '<!-- Source: src/components/modules/block-editor/motion/motionLibrary.ts (meta) -->',
  '',
  '# Motion effects catalog (agent memory)',
  '',
  'Allowlist of valid `data-motion` ids. Pick only from this file. Case pin /',
  'frame-scrub / Flip / mouse-parallax / carousel → T3 `useBlockMotion`',
  '(see `docs/landing-motion-foundation.md` §3b).',
  '',
  `Total effects: **${effects.length}**`,
  '',
  '## Index by category',
  '',
];

for (const cat of CATEGORY_ORDER) {
  const ids = byCategory.get(cat) ?? [];
  if (ids.length === 0) continue;
  lines.push(`- **${cat}**: ${ids.map(id => `\`${id}\``).join(', ')}`);
}

lines.push('', '## Allowlist (all ids)', '');
lines.push(effects.map(e => `\`${e.id}\``).join(', '));
lines.push('', '---', '');

for (const effect of effects) {
  const { meta } = effect;
  const prereq =
    meta.prerequisites.length === 0 ? '(none)' : meta.prerequisites.join('; ');
  const vs =
    meta.vs.length === 0
      ? '(none)'
      : meta.vs.map(v => `${v.id} — ${v.diff}`).join('; ');

  lines.push(`## \`${effect.id}\``);
  lines.push('');
  lines.push(`- category: ${meta.category}`);
  lines.push(`- appliesTo: ${effect.appliesTo.join(', ')}`);
  lines.push(`- tags: ${meta.tags.join(', ')}`);
  lines.push(`- summary: ${meta.summary}`);
  lines.push(`- whenToUse: ${meta.whenToUse.join('; ')}`);
  lines.push(`- whenNotToUse: ${meta.whenNotToUse.join('; ')}`);
  lines.push(`- vs: ${vs}`);
  lines.push(`- prerequisites: ${prereq}`);
  lines.push(`- relevantAttrs: ${meta.relevantAttrs.join(', ') || '(none)'}`);
  lines.push(`- defaults: ${formatDefaults(effect)}`);
  lines.push(`- example: \`${meta.example.replace(/`/g, '\\`')}\``);
  lines.push('');
}

process.stdout.write(lines.join('\n'));
